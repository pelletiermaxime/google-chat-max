#!/usr/bin/env python3
"""Regenerate the bundled Unicode catalog. Optional argument: local emoji-test.txt."""
import pathlib
import re
import sys
import urllib.request

VERSION = '18.0'
SOURCE = 'https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt'
root = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) > 1:
    source = pathlib.Path(sys.argv[1]).read_text()
else:
    with urllib.request.urlopen(SOURCE, timeout=30) as response:
        raw = response.read(2 * 1024 * 1024 + 1)
    if len(raw) > 2 * 1024 * 1024:
        raise SystemExit('Unicode source exceeds expected size')
    source = raw.decode('utf-8')
if f'# Version: {VERSION}' not in source:
    raise SystemExit('Unexpected Unicode version')
group = subgroup = ''
rows = []
for line in source.splitlines():
    if line.startswith('# group: '):
        group = line.removeprefix('# group: ')
    elif line.startswith('# subgroup: '):
        subgroup = line.removeprefix('# subgroup: ')
    elif '; fully-qualified' in line:
        codes, rest = line.split(';', 1)
        emoji = ''.join(chr(int(code, 16)) for code in codes.split())
        name = re.split(r' E[0-9.]+ ', rest.split('#', 1)[1], maxsplit=1)[1]
        rows.append('\t'.join([emoji, group, subgroup, name]))
if len(rows) != 3963 or len(set(row.split('\t')[0] for row in rows)) != len(rows):
    raise SystemExit('Unexpected or duplicate emoji entries')
header = f'# Generated by scripts/update-emojis.py; Unicode {VERSION}\n# Source: {SOURCE}\n# Copyright 2026 Unicode, Inc. See LICENSE.\n'
(root / 'internal/emojidata/emoji.tsv').write_text(header + '\n'.join(rows) + '\n')
print(f'Generated {len(rows)} fully qualified emoji')
